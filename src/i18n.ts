export function catalog(locale: string): Catalog {
  return MESSAGES[locale] ?? MESSAGES['en']!;
}

/** English base overlaid with the locale's overrides, so any key a translation
 *  hasn't localized yet degrades to English (never a raw key). The portal fetches
 *  this so every menu renders fully in the chosen language. */
export function mergedCatalog(locale: string): Catalog {
  return { ...MESSAGES['en']!, ...(MESSAGES[locale] ?? {}) };
}

export function t(locale: string, key: string, vars: Record<string, string | number> = {}): string {
  const c = catalog(locale);
  const template = c[key] ?? MESSAGES['en']![key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
